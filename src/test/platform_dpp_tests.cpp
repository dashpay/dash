UniValue LoadVectors(const unsigned char* data, size_t size)
{
    // Not read_json(): these vector files are JSON objects, not arrays.
    UniValue vectors;
    BOOST_REQUIRE(vectors.read(std::string(data, data + size)));
    BOOST_REQUIRE(vectors.isObject());
    return vectors;
}

std::vector<uint8_t> FromHex(const std::string& hex)
{
    BOOST_REQUIRE(IsHex(hex));
    return ParseHex(hex);
}

template <size_t N>
std::array<uint8_t, N> ArrayFromHex(const std::string& hex)
{
    const std::vector<uint8_t> bytes{FromHex(hex)};
    BOOST_REQUIRE_EQUAL(bytes.size(), N);
    std::array<uint8_t, N> out;
    std::copy(bytes.begin(), bytes.end(), out.begin());
    return out;
}

//! Deterministic signer over a fixed private key: RFC6979 compact
//! recoverable signature, exactly what interfaces::Wallet::signPlatformDigest
//! produces and what the vectors were signed with (dashcore::signer).
st::Signer MakeSigner(const std::string& privkey_hex, const uint256* expected_digest = nullptr)
{
    const std::vector<uint8_t> priv{FromHex(privkey_hex)};
    return [priv, expected_digest](const uint256& digest, std::vector<uint8_t>& sig_out) {
        if (expected_digest != nullptr) BOOST_CHECK_EQUAL(digest, *expected_digest);
        CKey key;
        key.Set(priv.begin(), priv.end(), /*fCompressedIn=*/true);
        if (!key.IsValid()) return false;
        return key.SignCompact(digest, sig_out);
    };
}

void CheckBuilt(const st::Result<st::BuiltTransition>& result, const UniValue& vec)
{
    BOOST_REQUIRE_MESSAGE(result.ok(), result.error);
    const std::vector<uint8_t> expected{FromHex(vec["serialized_hex"].get_str())};
    BOOST_CHECK_EQUAL(HexStr(result.value->bytes), HexStr(expected));
    // The wait handle is the single SHA256 of the serialized transition
    // (rs-dpp StateTransition::transaction_id).
    uint256 expected_hash;
    CSHA256().Write(expected.data(), expected.size()).Finalize(expected_hash.begin());
    BOOST_CHECK_EQUAL(result.value->hash, expected_hash);
}

uint256 DigestOf(const UniValue& vec)
{
    return uint256{FromHex(vec["digest_hex"].get_str())};
}

//! Document id: DSHA256(contract_id || owner_id || type_name || entropy),
//! per rs-dpp Document::generate_document_id_v0. Local mirror used to check
//! the document ids the bridge-built transitions must carry.
Identifier GenerateDocumentId(const Identifier& contract_id, const Identifier& owner_id,
                              const std::string& document_type_name, Span<const uint8_t> entropy)
{
    CHash256 hasher;
    hasher.Write(contract_id);
    hasher.Write(owner_id);
    hasher.Write(MakeUCharSpan(document_type_name));
    hasher.Write(entropy);
    uint256 hash;
    hasher.Finalize(hash);
    Identifier ret;
    std::copy(hash.begin(), hash.end(), ret.begin());
    return ret;
}

