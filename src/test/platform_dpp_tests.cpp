    const UniValue& vec{vectors["dashpay_contact_request"]};
    const std::string high_priv{vectors["keys"]["high"]["private_key_hex"].get_str()};
    const auto owner{ArrayFromHex<32>(vec["owner_id_hex"].get_str())};

    ContactRequest request;
    request.to_user_id = ArrayFromHex<32>(vec["to_user_id_hex"].get_str());
    request.encrypted_public_key = FromHex(vec["encrypted_public_key_hex"].get_str());
